let currentLang = localStorage.getItem("bejing_lang") || "tr";

function getCurrentLang() {
  return currentLang;
}

function t(key) {
  if (BEJING_I18N[currentLang] && BEJING_I18N[currentLang][key]) {
    return BEJING_I18N[currentLang][key];
  }
  return (BEJING_I18N.tr && BEJING_I18N.tr[key]) || key;
}

function setLanguage(lang) {
  if (lang !== "tr" && lang !== "ku") return;
  currentLang = lang;
  localStorage.setItem("bejing_lang", lang);
  document.documentElement.lang = (lang === "ku") ? "kmr" : "tr-TR";

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (key) {
      el.textContent = t(key);
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) {
      el.setAttribute("placeholder", t(key));
    }
  });

  document.querySelectorAll(".lang-btn").forEach(btn => {
    const target = btn.getAttribute("data-lang");
    if (target === lang) {
      btn.classList.add("active");
    } else {
      btn.classList.remove("active");
    }
  });

  
  // Update brand slogans dynamically
  const sloganText = (lang === "ku") ? "Dengê Jinên Ciwan" : "Genç Kadınların Sesi";
  document.querySelectorAll(".brand-slogan-dyn, #headerBrandSlogan, #footerBrandSlogan").forEach(el => {
    el.textContent = sloganText;
  });

  window.dispatchEvent(new CustomEvent("bejing:langChange", { detail: { lang } }));
}

document.addEventListener("DOMContentLoaded", () => {
  setLanguage(currentLang);
});
